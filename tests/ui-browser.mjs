import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium,devices} from 'playwright-core';

const origin=process.env.MAREA_URL??'http://127.0.0.1:4273/LA-MAREA-HUECA/';
const captures=resolve(process.env.MAREA_CAPTURES??'qa-ui');
await mkdir(captures,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.MAREA_CHROMIUM||undefined,args:process.env.MAREA_SOFTWARE==='1'?['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--single-process','--no-zygote']:[]});
try {
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
 await page.goto(origin+'?qa=1');
 assert.equal(await page.locator('#continue').isDisabled(),true);
 assert.match(await page.locator('#save-status').textContent(),/Sin partida local/);
 await page.screenshot({path:resolve(captures,'menu-1280.png')});
 await page.getByRole('button',{name:'Ajustes'}).click();
 await page.getByLabel('Música').fill('32');
 await page.getByRole('button',{name:'Volver'}).click();
 assert.equal(await page.locator('#panel').evaluate(e=>e.open),false);
 await page.getByRole('button',{name:'Controles'}).click();
 await page.getByText('Mochila / cuaderno').waitFor();
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#panel').evaluate(e=>e.open),false);
 await page.getByRole('button',{name:'Créditos'}).click();
 await page.getByRole('button',{name:'Volver'}).click();
 await page.getByRole('button',{name:'Nueva partida'}).click();
 await page.getByRole('button',{name:'Entrar en la cuenca'}).click();
 await page.getByRole('button',{name:'Capturar cursor'}).click();
 await page.waitForFunction(()=>window.mareaQA.state().mode==='play');
 await page.keyboard.press('e');
 await page.getByText('Fabricación',{exact:true}).waitFor();
 await page.screenshot({path:resolve(captures,'mochila-1280.png')});
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Controles'}).click();
 await page.getByRole('button',{name:'Volver'}).click();
 await page.getByRole('button',{name:'Guardar'}).click();
 await page.getByRole('button',{name:'Volver al menú'}).click();
 assert.equal(await page.locator('#continue').isEnabled(),true);
 assert.match(await page.locator('#save-status').textContent(),/Partida local disponible/);
 await page.screenshot({path:resolve(captures,'menu-guardado.png')});
 await page.getByRole('button',{name:'Continuar'}).click();
 await page.getByRole('button',{name:'Capturar cursor'}).waitFor();
 assert.equal((await page.evaluate(()=>window.mareaQA.state())).saved,true);
 assert.deepEqual(errors,[]);
 const mobile=await browser.newPage({...devices['iPhone 13']});
 await mobile.goto(origin);
 await mobile.screenshot({path:resolve(captures,'menu-390.png')});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await mobile.getByRole('button',{name:'Controles'}).click();
 await mobile.screenshot({path:resolve(captures,'controles-390.png')});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 console.log('UI: portada, ajustes, guía, créditos, nueva partida, mochila, pausa, guardado, continuar y ventana estrecha correctos.');
} finally {await browser.close();}
